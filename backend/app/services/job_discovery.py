# --- FRAUD, SCAM & TRAINING INSTITUTE BLACKLIST ---
BLACKLISTED_COMPANIES = {
    "dexter", "dexterity", "thinknova", "recruitdiary", "talentrabbit",
    "training institute", "placement guarantee", "pay after placement",
    "unpaid", "training program", "consultancy", "staffing solution",
    "course with placement", "placement consultancy"
}

def is_blacklisted_or_fake(company: str, description: str = "") -> bool:
    """Returns True if company or description matches known training/scam/unpaid firms."""
    comp_lower = (company or "").lower().strip()
    desc_lower = (description or "").lower()
    for b in BLACKLISTED_COMPANIES:
        if b in comp_lower or b in desc_lower:
            return True
    return False

